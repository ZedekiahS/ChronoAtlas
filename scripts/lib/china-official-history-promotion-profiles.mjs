export const officialHistoryPromotionProfiles = new Map(
  profiles.map((profile) => [profile.id, Object.freeze({
    ...profile,
    generatorId: `promote-source-event-cards:${profile.id}`,
  })]),
);

export function getOfficialHistoryPromotionProfile(profileId = defaultOfficialHistoryPromotionProfileId) {
  const profile = officialHistoryPromotionProfiles.get(profileId);
  if (!profile) {
    throw new Error(
      `Unknown official-history promotion profile: ${profileId}. `
      + `Available profiles: ${[...officialHistoryPromotionProfiles.keys()].join(", ")}`,
    );
  }
  return profile;
}

export function requestedOfficialHistoryPromotionProfile(args = process.argv.slice(2)) {
  const profileId = args
    .find((argument) => argument.startsWith("--profile="))
    ?.slice("--profile=".length);
  return getOfficialHistoryPromotionProfile(profileId || defaultOfficialHistoryPromotionProfileId);
}
